import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const text = fs.readFileSync(new URL('../src/data/step2/medicine.js', import.meta.url),'utf8');
const allQuestions = JSON.parse(text.split('export default ')[1].replace(/;\s*$/,''));
const questions = allQuestions.filter(q=>!q.duplicateOf);
const BANKS={s2med:{questions,allQuestions}};
const storage=new Map();
const context=vm.createContext({BANKS,key:x=>x,localStorage:{getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v)}});
const component=fs.readFileSync(new URL('../src/components/Questions.jsx',import.meta.url),'utf8');
vm.runInContext(component.slice(component.indexOf('function storageKey('),component.indexOf('export default function Questions()')),context);
const saved={queue:[{...questions[2],a:'old content'},questions[0]],current:1,score:{correct:1,wrong:1},results:{0:'wrong',1:'correct'},missed:[{...questions[2],a:'old content'}],category:'All'};
storage.set('validmed_step2_q_s2med',JSON.stringify(saved));
storage.set('validmed_step2_flags',JSON.stringify([questions[2].id]));
const before=storage.get('validmed_step2_q_s2med');
const loaded=context.loadState('s2med');
assert.deepEqual(Array.from(loaded.queue.slice(0,2),q=>q.id),saved.queue.map(q=>q.id));
assert.equal(loaded.queue[0].a,questions[2].a);
assert.equal(loaded.current,1);
assert.deepEqual(JSON.parse(JSON.stringify(loaded.score)),saved.score);
assert.deepEqual(JSON.parse(JSON.stringify(loaded.results)),saved.results);
assert.equal(loaded.missed[0].id,questions[2].id);
assert.equal(context.collectMissed()[0].a,questions[2].a);
assert.equal(context.collectFlagged()[0].id,questions[2].id);
assert.equal(loaded.queue.length,1119);
assert.equal(new Set(loaded.queue.map(q=>q.id)).size,1119);
assert.equal(storage.get('validmed_step2_q_s2med'),before);
assert.equal(allQuestions.length,1119);
console.log('PASS: Medicine IDs, old order/current/marks/score/missed/flags preserved; content hydrates and new cards append without writing storage.');
